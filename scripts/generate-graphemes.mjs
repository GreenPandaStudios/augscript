#!/usr/bin/env node
// Maintainer-only Unicode generation. Ordinary compilation uses the committed table.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'..'),directory=join(root,'native/unicode/18.0.0');
if(process.argv.slice(2).some(arg=>arg!=='--check')||process.argv.slice(2).length>1)throw new Error('Usage: node scripts/generate-graphemes.mjs [--check]');
const manifest=JSON.parse(readFileSync(join(directory,'inputs.json'),'utf8'));
const names=['GraphemeBreakProperty.txt','emoji-data.txt','DerivedCoreProperties.txt','GraphemeBreakTest.txt','ReadMe.txt','LICENSE.txt'];
if(manifest.format!==1||manifest.version!=='18.0.0'||manifest.annexRevision!==49||JSON.stringify(Object.keys(manifest.sources).sort())!==JSON.stringify(names.slice().sort()))throw new Error('Unsupported Unicode input manifest; review the algorithm and all data together');
const inputs={};
for(const name of names){
  const bytes=readFileSync(join(directory,name)),pin=manifest.sources[name];
  if(typeof pin.url!=='string'||!pin.url.startsWith('https://www.unicode.org/')||!/^[a-f0-9]{64}$/.test(pin.sha256)||createHash('sha256').update(bytes).digest('hex')!==pin.sha256)throw new Error('Unicode input integrity failed: '+name);
  inputs[name]=bytes.toString('utf8');
}
for(const [name,marker] of [['GraphemeBreakProperty.txt','# GraphemeBreakProperty-18.0.0.txt'],['DerivedCoreProperties.txt','# DerivedCoreProperties-18.0.0.txt'],['emoji-data.txt','# Version: 18.0.0'],['GraphemeBreakTest.txt','# GraphemeBreakTest-18.0.0.txt'],['ReadMe.txt','final data files for version 18.0.0']])if(!inputs[name].includes(marker))throw new Error('Unicode version mismatch: '+name);
if(!inputs['LICENSE.txt'].startsWith('UNICODE LICENSE V3\n')||inputs['LICENSE.txt'].includes('*/'))throw new Error('Unsupported Unicode license notice');
const classes=['Other','CR','LF','Control','Extend','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT','ZWJ'];
const conjuncts=['None','Consonant','Extend','Linker'];
const properties=new Uint8Array(0x110000);
function assign(name,select,mask){
  const seen=new Uint8Array(properties.length);
  for(const [index,line] of inputs[name].split(/\r?\n/).entries()){
    const content=line.split('#')[0].trim();if(!content)continue;
    const fields=content.split(';').map(field=>field.trim()),bits=select(fields);if(bits===undefined)continue;
    const range=/^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?$/.exec(fields[0]);
    if(!range)throw new Error('Invalid Unicode range: '+name+':'+(index+1));
    const first=parseInt(range[1],16),last=parseInt(range[2]??range[1],16);
    if(last<first||last>=properties.length)throw new Error('Unicode range out of bounds: '+name+':'+(index+1));
    for(let point=first;point<=last;point++){
      if(seen[point])throw new Error('Overlapping Unicode property: '+name+':'+(index+1));
      seen[point]=1;properties[point]=(properties[point]&~mask)|bits;
    }
  }
}
assign('GraphemeBreakProperty.txt',fields=>{if(fields.length!==2||!classes.includes(fields[1]))throw new Error('Unknown grapheme property');return classes.indexOf(fields[1]);},15);
assign('emoji-data.txt',fields=>fields[1]==='Extended_Pictographic'?16:undefined,16);
assign('DerivedCoreProperties.txt',fields=>{if(fields[1]!=='InCB')return undefined;if(fields.length!==3||!conjuncts.includes(fields[2]))throw new Error('Unknown Indic conjunct property');return conjuncts.indexOf(fields[2])<<5;},96);
const ranges=[];
for(let first=0;first<properties.length;){let last=first;while(last+1<properties.length&&properties[last+1]===properties[first])last++;if(properties[first])ranges.push([first,last,properties[first]]);first=last+1;}
const hex=value=>'0x'+value.toString(16);
const generated='/* Generated by scripts/generate-graphemes.mjs from pinned Unicode 18.0.0 data.\n'+inputs['LICENSE.txt'].split('\n').map(line=>line?' * '+line:' *').join('\n')+'\n */\n#ifndef AUG_GRAPHEME_DATA_H\n#define AUG_GRAPHEME_DATA_H\n'+
  '#define AUG_GRAPHEME_UNICODE_VERSION "18.0.0"\n#define AUG_GRAPHEME_ANNEX_REVISION 49\n'+
  'enum AugGraphemeClass { '+classes.map((name,index)=>'AUG_GCB_'+name.toUpperCase()+'='+index).join(', ')+' };\n'+
  'enum AugIndicConjunct { '+conjuncts.map((name,index)=>'AUG_INCB_'+name.toUpperCase()+'='+index).join(', ')+' };\n'+
  '#define AUG_GCB_MASK 15u\n#define AUG_EXTENDED_PICTOGRAPHIC 16u\n#define AUG_INCB_SHIFT 5u\n'+
  'typedef struct { uint32_t first, last; unsigned char properties; } AugGraphemeRange;\n'+
  'static const AugGraphemeRange aug_grapheme_ranges[] = {\n'+ranges.map(([first,last,bits])=>'  {'+hex(first)+', '+hex(last)+', '+bits+'},').join('\n')+'\n};\n#endif\n';
const version='// Generated by scripts/generate-graphemes.mjs. Update the pinned data and algorithm together.\nexport const graphemeUnicodeVersion = "18.0.0";\nexport const graphemeAnnexRevision = 49;\n';
for(const [file,content] of [['runtime/aug_grapheme_data.h',generated],['src/unicode-version.ts',version],['runtime/UNICODE-LICENSE.txt',inputs['LICENSE.txt']]]){
  const path=join(root,file);
  if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==content)throw new Error('Unicode generated output is stale: '+file);}else writeFileSync(path,content);
}
console.log('Unicode 18.0.0 grapheme data: '+ranges.length+' ranges'+(process.argv.includes('--check')?' verified':' generated'));
