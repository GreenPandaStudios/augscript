const markdown=(text:string)=>text.replace(/[\\\`*_[\]<>|]/g,char=>'\\'+char);
// Display punctuation avoids Mermaid control characters without exposing encoded
// entities in SVG text. The exact expressions remain linked in source and specs.
const punctuation:Record<string,string>={'&':'＆',';':'；','"':'”','<':'‹','>':'›','{':'｛','}':'｝','[':'［',']':'］','`':'′','#':'＃','\\':'＼','|':'｜'};
const label=(text:string)=>text.replace(/\s+/g,' ').replace(/^(.{117}).{4,}$/,'$1…').replace(/[&;"<>{}\[\]`#\\|]/g,char=>punctuation[char]);
// Break long messages at word boundaries. Global Mermaid wrapping also wraps
// narrow branch frames and actor names, which can turn labels into columns.
const sequenceLabel=(text:string,width=56)=>{
  const lines:string[]=[],words=label(text).split(' ');let line='';
  for(const word of words){
    if(line&&line.length+word.length+1>width){lines.push(line);line=word;}
    else line+=(line?' ':'')+word;
  }
  if(line)lines.push(line);
  return lines.join('<br/>');
};
