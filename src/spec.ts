const generated = '<!-- Generated by aug spec. Edit the August source, then regenerate. -->';
const copied = '// Generated by aug spec. This is a copy of the installed dependency source.\n';
const code = (value: string) => {const text=value.replaceAll('\n','\\n');const fence='`'.repeat(1+Math.max(0,...(text.match(/`+/g)??[]).map(part=>part.length)));return fence+(text.startsWith('`')?' ':'')+text+(text.endsWith('`')?' ':'')+fence;};
const url = (value: string) => value.replaceAll('\\', '/').split('/').map(encodeURIComponent).join('/');
const anchor = (name: string) => 'symbol-' + name;
const hash = (text: string) => createHash('sha256').update(text).digest('hex');
const compare = (left:string, right:string) => left < right ? -1 : left > right ? 1 : 0;
const unreachable = (node: never): never => { throw new Error(`No specification renderer for ${(node as {kind?:string}).kind}`); };

export interface SpecOutput { path: string; text: string; source: string }
export interface SpecOptions { files?: SourceFile[]; manifest?: boolean }

/** Render checked code, never execute it. All paths and ordering are reproducible. */
export function generateSpecs(checked: CheckedProject, options: SpecOptions = {}): SpecOutput[] {
  if (checked.diagnostics.some(issue => issue.severity !== 'warning')) throw new Error('Fix compiler errors before generating specifications');
  const project = checked.project;
  const owned = options.files ?? [...project.files.values()].filter(file => !file.builtin && !file.package);
  const own = new Set(owned.map(file => file.path));
  const docs = new Map<string,string>(), sources = new Map<string,string>();
  for (const file of project.files.values()) {
    if (own.has(file.path)) { docs.set(file.path, file.path + '.md'); sources.set(file.path, file.path); continue; }
    const scope = file.package && project.packages.scopes.get(file.package);
    const identity = scope ? join('packages', scope.name, scope.version, relative(scope.sourceRoot, file.path)) :
      join('august', compilerVersion(), libraryRelative(project.libraries, file.path));
    const source = join(project.root, '.aug-spec', identity);
    docs.set(file.path, source + '.md'); sources.set(file.path, source);
  }
  const queue = [...owned].sort((a,b) => compare(a.path,b.path));
  const seen = new Set<string>(), outputs: SpecOutput[] = [];
  for (let index = 0; index < queue.length; index++) {
    const file = queue[index]; if (seen.has(file.path)) continue; seen.add(file.path);
    const writer = new SpecWriter(checked, file, docs, sources, own, path => {
      const dependency = project.files.get(path);
      if (dependency && !seen.has(path)) queue.push(dependency);
    });
    outputs.push({path:docs.get(file.path)!, text:writer.render(), source:file.path});
    if (!own.has(file.path)) outputs.push({path:sources.get(file.path)!, text:copied + file.source, source:file.path});
  }
  return outputs.sort((a,b) => compare(a.path,b.path));
}

class SpecWriter {
  private checked: CheckedProject;
  private file: SourceFile;
  private docs: Map<string,string>;
  private sources: Map<string,string>;
  private own: Set<string>;
  private enqueue: (path:string) => void;
  private used = new Map<string,{def:Definition; operations:Set<MethodDecl>; fields:Set<string>; constructed?:boolean}>();
  private builtins = new Map<string,BuiltinOperation>();
  private properties = new Map<string,{type:string;documentation:string}>();
  private locals = new Map<string,TypeRef>();
  constructor(checked:CheckedProject, file:SourceFile, docs:Map<string,string>, sources:Map<string,string>, own:Set<string>, enqueue:(path:string)=>void) {
    this.checked=checked; this.file=file; this.docs=docs; this.sources=sources; this.own=own; this.enqueue=enqueue;
  }
  private definition(name:string): Definition|undefined { return this.checked.project.scopes.get(this.file.path)?.get(name); }
  private use(def:Definition|undefined, method?:MethodDecl, field?:string): void {
    if (!def || def.file === this.file.path) return;
    if(method&&'methods' in def.node&&!def.node.methods.includes(method)) {
      const owner=[...this.checked.project.definitions.values()].find(owner=>'methods' in owner.node&&owner.node.methods.includes(method!));
      this.use(owner,method); method=undefined;
    }
    let entry=this.used.get(def.id);
    if(!entry) {entry={def,operations:new Set(),fields:new Set()};this.used.set(def.id,entry);}
    if(method)entry.operations.add(method); if(field)entry.fields.add(field);
    this.enqueue(def.file);
  }
  private link(def:Definition, name=def.name, label=name): string {
    this.use(def);
    return `[${code(label)}](${url(relative(dirname(this.docs.get(this.file.path)!),this.docs.get(def.file)!))}#${encodeURIComponent(anchor(name))})`;
  }
  private source(span:Span): string {
    return `[source](${url(relative(dirname(this.docs.get(this.file.path)!),this.sources.get(span.file)!))}#L${span.line + (this.own.has(span.file)?0:1)})`;
  }
  private heading(name:string, span:Span, level:number, children:SpecNode[], role?:string): SpecNode {
    return section(code(name)+(role?' · '+role:''),level,children,anchor(name),this.source(span));
  }
  private type(type:TypeRef, file=this.file.path): string {
    const def=this.checked.project.scopes.get(file)?.get(type.name);this.use(def);type.args.forEach(arg=>this.type(arg,file));
    return def?this.link(def,def.name,typeName(type)):code(typeName(type));
  }
  private notes(doc?:Javadoc): string {
    if(!doc)return '';
    const prose=doc.markdown.split(/(?:^|\n\n)\*\*(?:Returns|Parameters|Throws|Deprecated:|See also:)/)[0].trim();
    const extra=(doc.tags??[]).filter(tag=>tag.name==='deprecated'||tag.name==='see').map(tag=>
      tag.name==='deprecated'?`Deprecated: ${tag.value}`:`See also: ${tag.value}`);
    return [prose,...extra].filter(Boolean).join(' ');
  }
  private generics(node:GenericHeader): string {
    return node.typeParams.length ? 'Type parameters: ' + node.typeParams.map(name=>code(name)+
      (node.typeVariance?.[name]?` (${node.typeVariance[name] === 'out' ? 'produces values' : 'accepts values'})`:'')+
      (node.typeConstraints?.[name]?.length?` must satisfy ${node.typeConstraints[name].map(type=>this.type(type)).join(' and ')}`:'')).join('; ')+'.':'';
  }
  private inputs(params:Param[], fields=false, file=this.file.path, descriptions=new Map<string,string>()): string {
    if(!params.length)return '';
    return '**Inputs:** '+params.map(param=>{
      this.locals.set(param.name,param.type);
      const name=code(param.label??param.name), type=this.type(param.type,file);
      let sentence=param.injected?`Resolve ${type} as ${name}`:`Take ${name} (${type})`;
      if(param.source)sentence+=` from HTTP ${param.source.kind}${param.source.name?' '+code(param.source.name):''}`;
      if(param.type.optional)sentence+='; omitted means null';
      if(param.ownership==='own')sentence+='; take ownership';
      else if(param.ownership==='borrow')sentence+='; allow mutation during the call';
      if(fields)sentence+=`; store ${param.mutable?'mutably':'read-only'}${param.name.startsWith('_')?' and privately':''}${param.label&&param.label!==param.name?' as '+code(param.name):''}`;
      const description=descriptions.get(param.name);
      if(description)sentence+=' — '+description.replace(/[.!?]$/,'');
      return sentence+'.';
    }).join(' ');
  }
  private contract(method:MethodDecl, documentation?:Javadoc): SpecNode[] {
    const effects=this.checked.effectContracts.get(method);
    const layers=this.checked.interceptorPlans.get(method)??[];
    const errors=[...new Set([...method.throws.map(type=>{this.type(type,method.span.file);return typeName(type);}),...layers.flatMap(layer=>layer.errors.map(tyName))])];
    const changes=effects?.changes??method.changes??[];
    const uses=[...(effects?.uses.values()??method.uses??[])];
    const result:SpecNode[]=[];
    const generics=this.generics(method), inputs=this.inputs(method.params,false,method.span.file,documentation?.parameters);
    if(generics)result.push(paragraph(generics));
    if(inputs)result.push(paragraph(inputs));
    const facts:string[]=[];
    const returnNote=documentation?.tags?.find(tag=>tag.name==='return'||tag.name==='returns')?.value??
      documentation?.markdown.match(/\*\*Returns\*\* ([^\n]+)/)?.[1];
    if(method.returns.name!=='void')facts.push(`Returns ${(method.returnOwnership==='own'?'ownership of ':'')+this.type(method.returns,method.span.file)}`+
      (returnNote?` — ${returnNote.replace(/[.!?]$/,'')}`:'')+'.');
    if(changes.length)facts.push('Changes '+changes.map(code).join(', ')+'.');
    if(uses.length)facts.push('Uses '+uses.map(effect=>{
      const def='capability' in effect?effect.capability?.def:undefined;
      const target=def??this.definition(effect.source);
      const operation=target&&'methods' in target.node?target.node.methods.find(method=>method.name===effect.operation):undefined;
      this.use(target,operation);
      return target?this.link(target,operation?`${target.name}.${operation.name}`:target.name,`${effect.source}.${effect.operation}`):code(`${effect.source}.${effect.operation}`);
    }).join(', ')+'.');
    if(errors.length)facts.push('Can fail with '+errors.map(name=>{
      const note=documentation?.tags?.find(tag=>(tag.name==='throws'||tag.name==='exception')&&tag.value.startsWith(name+' '))?.value.slice(name.length).trim()??
        documentation?.markdown.split('**Throws**\n')[1]?.split('\n\n')[0]?.split('\n').find(line=>line.startsWith('- '+code(name)+': '))?.slice(('- '+code(name)+': ').length);
      return code(name)+(note?` (${note.replace(/[.!?]$/,'').replace(/^When\b/,'when')})`:'');
    }).join(', ')+'.');
    if(facts.length)result.push(paragraph(facts.join(' ')));
    if(method.endpoint) {
      const endpoint=method.endpoint;
      result.push(paragraph(`HTTP route: ${code(endpoint.method)} ${code(endpoint.path)}. `+
        (endpoint.streams?`Stream ${this.type(method.returns)} items. `:`Use status ${endpoint.status} when the handler returns a body; a returned HttpResponse can set its own status. `)+
        'An unhandled request failure returns status 500 and cancels its request tasks.'));
      if(endpoint.errors.length)result.push(paragraph('Declared HTTP failures: '+endpoint.errors.map(error=>`${this.type(error.type)} returns status ${error.status}`).join('; ')+'.'));
    }
    return result;
  }
  private layers(node:MethodDecl|ClassDecl): SpecNode[] {
    const layers=this.checked.interceptorPlans.get(node)??[];
    const policies=node.kind==='function'?this.checked.httpPolicies.get(node)??[]:[];
    if(!layers.length&&!policies.length)return [];
    const steps:string[]=[];
    policies.forEach(policy=>{steps.push(this.policy(policy)+
      (node.kind==='function'&&policy.dependencies.length?' Use '+policy.dependencies.map(index=>code(node.params[index].name)).join(', ')+'.':''));});
    layers.forEach(layer=>{this.use(layer.definition,layer.around);steps.push(`Call ${this.link(layer.definition,`${layer.definition.name}.around`)}.`+
      (layer.annotation.mappings.length?' Map '+layer.annotation.mappings.map(mapping=>code(mapping.source)+' to '+code(mapping.name)).join(', ')+'.':''));});
    return [paragraph('Layers run in this order:'),list(steps,true),
      ...(policies.length?[paragraph('HTTP policies run before decoding; custom interceptors run after it.')]:[])];
  }
  private policy(policy:HttpPolicyPlan): string {
    const options=policy.options;
    switch(policy.name) {
      case 'RequireLogin':return 'Authenticate the request. If no identity is returned, finish with status 401.';
      case 'RequirePermission':return `Authenticate the request and authorize permission ${code(String(options.permission))}. No identity returns 401; denied permission returns 403.`;
      case 'LogRequest':return 'Call the request logger after transport completion or disconnect, in reverse layer order. Record disconnect as status 499. This layer observes rejections from layers inside it.';
      case 'RateLimit':return `Allow ${options.requests} requests per ${options.seconds} seconds for each endpoint and trusted transport peer. Ignore forwarding headers. Excess requests return 429.`;
      case 'Timeout':return `Set a deadline of ${options.milliseconds} milliseconds for the handler, child tasks, and response transport. Before output, expiry returns 504; after output, it closes the stream. Native calls finish before cooperative cancellation; buffered request reception precedes this deadline.`;
      case 'Cors':return `Allow origins ${code(JSON.stringify(options.origins))}. ${options.credentials?'Allow':'Do not allow'} credentials. `+
        (options.headers?`Allow request headers ${code(JSON.stringify(options.headers))}. `:'')+'A supplied disallowed origin returns 403. Preflight checks the route method and requested headers.';
      case 'Compress':return 'Negotiate gzip. Respect existing Content-Encoding and bodyless statuses. Encode stream items as complete concatenated gzip members.';
    }
  }
  private receiver(expr:Expr): Definition|undefined {
    const checked=this.checked.expressionTypes.get(expr)?.def;
    if(checked)return checked;
    const ref=expr.kind==='name'?this.locals.get(expr.name):undefined;
    if(ref)return this.definition(ref.name);
    if(expr.kind==='resolve')return this.checked.bindings.find(binding=>binding.key===expr.name)?.exposedType.def;
    if(expr.kind==='call'&&expr.callee.kind==='name') {
      const def=this.definition(expr.callee.name);
      if(def?.node.kind==='class')return def;
      if(def?.node.kind==='function')return this.definition(def.node.returns.name);
    }
    return undefined;
  }
  private method(def:Definition, name:string, seen=new Set<string>()): MethodDecl|undefined {
    if(seen.has(def.id))return;seen.add(def.id);
    if(!('methods' in def.node))return;
    const direct=def.node.methods.find(method=>method.name===name);if(direct)return direct;
    const refs=def.node.kind==='class'?def.node.implements:def.node.kind==='interface'?def.node.extends:[];
    for(const ref of refs){const parent=this.checked.project.scopes.get(def.file)?.get(ref.name);const inherited=parent&&this.method(parent,name,seen);if(inherited)return inherited;}
  }
  private expression(expr:Expr, nested=false): string {
    switch(expr.kind) {
      case 'literal':return expr.value===null?'null':code(expr.numericText??JSON.stringify(expr.value));
      case 'name': {const def=!this.locals.has(expr.name)?this.definition(expr.name):undefined;this.use(def);return def?this.link(def):code(expr.name);}
      case 'member': {
        const def=this.receiver(expr.object);this.use(def,undefined,expr.name);
        const name=expr.name,receiverType=this.checked.expressionTypes.get(expr.object)?.name;
        const property=receiverType&&builtinProperties[receiverType]?.find(property=>property.name===name);
        if(property)this.properties.set(receiverType+'.'+name,{...property,type:this.checked.expressionTypes.get(expr)?tyName(this.checked.expressionTypes.get(expr)!):property.type});
        return `${code(name)} of ${this.expression(expr.object)}`;
      }
      case 'unary': {
        if(expr.op==='!'&&expr.value.kind==='binary'&&(expr.value.op==='=='||expr.value.op==='!='))
          return `${this.expression(expr.value.left,true)} ${expr.value.op==='=='?'does not equal':'equals'} ${this.expression(expr.value.right,true)}`;
        return `${expr.op==='!'?'not':'the negative of'} (${this.expression(expr.value)})`;
      }
      case 'binary': {
        const words:Record<string,string>={'+':'plus','-':'minus','*':'times','/':'divided by','==':'equals','!=':'does not equal','<':'is less than','>':'is greater than','<=':'is at most','>=':'is at least','&&':'and','||':'or'};
        if(!words[expr.op])throw new Error(`No specification renderer for operator ${expr.op}`);
        const textParts=this.stringParts(expr);
        if(expr.op==='+'&&textParts.length>=3) {
          const parts=textParts.map(part=>this.expression(part));
          return 'text that joins '+parts.slice(0,-1).join(', ')+' and '+parts.at(-1);
        }
        const result=`${this.expression(expr.left,expr.left.kind==='binary')} ${words[expr.op]} ${this.expression(expr.right,expr.right.kind==='binary')}`;
        return nested?`(${result})`:result;
      }
      case 'collection': {
        if(expr.collection==='Map')return 'a map with '+expr.items.filter((_,index)=>index%2===0).map((key,index)=>`${this.expression(key)} mapped to ${this.expression(expr.items[index*2+1])}`).join('; ');
        return `a ${expr.collection==='empty'?'context-typed empty collection':expr.collection.toLowerCase()}`+(expr.items.length?' containing '+expr.items.map(item=>this.expression(item)).join(', '):' with no items');
      }
      case 'resolve':return `the instance provided for ${code(expr.name)}${expr.typeArgs.length?' with type arguments '+expr.typeArgs.map(type=>this.type(type)).join(', '):''}`;
      case 'call': {
        const action=this.call(expr);
        return action.startsWith('construct ')?'a new '+action.slice('construct '.length):
          action.startsWith('call ')?'the result of '+action.slice('call '.length):action;
      }
      case 'start':return `a child task running ${this.expression(expr.call)} with its inputs captured now`;
      case 'wait':return `the result of waiting for ${expr.tasks.map(task=>this.expression(task)).join(' and ')}${expr.tasks.length>1?' in input order':''}; propagate failures`;
      case 'handle': {const plan=this.checked.actions.get(expr);return `a deferred HTTP form action for ${plan?this.link(plan.endpoint):this.expression(expr.call)}`+
        (expr.call.kind==='call'&&expr.call.args.length?'; inputs: '+expr.call.args.map((value,index)=>(expr.call.kind==='call'?code(expr.call.argLabels[index]??(value.kind==='name'?value.name:String(index+1)))+' from ':'')+this.expression(value)).join('; '):'')+
        '; capture supplied values when rendering, and read form inputs when submitted; send the form to that endpoint with its declared HTTP method';}
      case 'formInput':return 'the checked form input supplied when the HTTP form is submitted';
      case 'markupText':return code(expr.text);
      case 'markup': {
        const def=this.definition(expr.tag);this.use(def);
        return (def?'the server component '+this.link(def):'the HTML element '+code(expr.tag||'fragment'))+
          (expr.attributes.length?' with '+expr.attributes.map(attribute=>`${code(attribute.name)} = ${this.expression(attribute.value)}`).join(', '):'')+
          (expr.children.length?' containing '+expr.children.map(child=>this.expression(child)).join(', '):'')+
          ' (server-rendered; text escaped)';
      }
      default:return unreachable(expr);
    }
  }
  private call(expr:Extract<Expr,{kind:'call'}>): string {
    if(expr.callee.kind==='name'&&['List','Set','Map'].includes(expr.callee.name)&&!this.definition(expr.callee.name)) {
      const name=expr.callee.name, types=expr.typeArgs.map(type=>this.type(type));
      const items=expr.args.map(arg=>this.expression(arg));
      const label=name==='Map'?'map from '+(types[0]??'any')+' to '+(types[1]??'any'):
        name.toLowerCase()+' of '+(types[0]??'any');
      return items.length?'a '+label+' containing '+items.join(', '):'an empty '+label;
    }
    let target:string, method:MethodDecl|undefined, constructs=false;
    if(expr.callee.kind==='name') {
      const name=expr.callee.name;
      const def=this.definition(expr.callee.name);this.use(def);
      if(def?.node.kind==='class'&&def.file!==this.file.path)this.used.get(def.id)!.constructed=true;
      constructs=def?.node.kind==='class'||!def&&Object.hasOwn(builtinTypes,name);
      method=def?.node.kind==='function'?def.node:undefined;
      const builtin=!def&&builtinFunctions.find(operation=>operation.name===name);
      if(builtin)this.builtins.set(builtin.name,builtin);
      target=def?this.link(def):code(expr.callee.name);
    }else if(expr.callee.kind==='member') {
      const name=expr.callee.name;
      const def=this.receiver(expr.callee.object);method=def&&this.method(def,expr.callee.name);this.use(def,method);
      const receiver=this.checked.expressionTypes.get(expr.callee.object);
      const receiverType=receiver?.name??(expr.callee.object.kind==='name'?this.locals.get(expr.callee.object.name)?.name:undefined);
      const builtin=!def&&receiverType&&collectionOperations[receiverType]?.find(operation=>operation.name===name);
      if(builtin)this.builtins.set((receiver?tyName(receiver):receiverType)+'.'+builtin.name,{
        ...builtin,
        parameters:builtin.parameters.map(param=>({...param,type:receiver?tyName(operationType(param.type,receiver)):param.type})),
        returns:this.checked.expressionTypes.get(expr)?tyName(this.checked.expressionTypes.get(expr)!):builtin.returns,
      });
      // An inherited operation links to the interface that actually declares it.
      const owner=method&&[...this.checked.project.definitions.values()].find(def=>'methods' in def.node&&def.node.methods.includes(method!));
      this.use(owner,method);
      target=(owner?this.link(owner,`${owner.name}.${method!.name}`):code(expr.callee.name))+' on '+this.expression(expr.callee.object);
    }else target=this.expression(expr.callee);
    expr.typeArgs.forEach(type=>this.type(type));
    const plan=this.checked.callPlans.get(expr);
    const parameters=method?.params??(expr.callee.kind==='name'&&this.definition(expr.callee.name)?.node.kind==='class'?
      (this.definition(expr.callee.name)!.node as ClassDecl).fields:[]);
    const inputs=expr.args.map((arg,index)=>{
      const slot=plan?.sourceIndices.indexOf(index);
      const label=expr.argLabels[index]??(slot!==undefined&&slot>=0?parameters[slot]?.label??parameters[slot]?.name:arg.kind==='name'?arg.name:undefined);
      return (label&&!(arg.kind==='name'&&arg.name===label)?code(label)+' as ':'')+this.expression(arg);
    });
    let text=`${constructs?'construct':'call'} ${target}`+(expr.typeArgs.length?' with type arguments '+expr.typeArgs.map(type=>this.type(type)).join(', '):'')+(inputs.length?' with '+inputs.join(', '):'');
    const injected=parameters.flatMap((param,index)=>{
      if(!param.injected)return [];
      const source=plan?.injectionSources?.[index]??plan?.bindingKeys[index]??typeName(param.type);
      return [code(source)+(source===param.name?'':' for '+code(param.name))];
    });
    if(injected.length)text+=' using '+injected.join(', ');
    return text;
  }
  private stringParts(expr:Expr): Expr[] {
    if(expr.kind==='binary'&&expr.op==='+'&&this.checked.expressionTypes.get(expr)?.name==='string')
      return [...this.stringParts(expr.left),...this.stringParts(expr.right)];
    return [expr];
  }
  private joinedText(target:string, value:Expr): FlowNode|undefined {
    const parts=this.stringParts(value);
    if(parts.length<4)return;
    const items=parts.map(part=>this.expression(part));
    if(items.length>=6)return sequence(`Join these parts in order to make ${target}`,items);
    return step(`Join ${items.slice(0,-1).join(', ')} and ${items.at(-1)} to make ${target}.`);
  }
  private headerFields(value:Expr): {base:Expr; fields:string[]}|undefined {
    let current=value;
    const calls:Extract<Expr,{kind:'call'}>[]=[];
    while(current.kind==='call'&&current.callee.kind==='member'&&current.callee.name==='with'&&
      this.checked.expressionTypes.get(current.callee.object)?.name==='Headers') {
      const labels=current.args.map((arg,index)=>current.kind==='call'?
        current.argLabels[index]??(arg.kind==='name'?arg.name:''):''),
        name=labels.indexOf('name'),value=labels.indexOf('value');
      if(name<0||value<0)return;
      calls.unshift(current);
      current=current.callee.object;
    }
    if(calls.length<3)return;
    const operation=collectionOperations.Headers?.find(operation=>operation.name==='with');
    if(operation)this.builtins.set('Headers.with',operation);
    return {base:current,fields:calls.map(call=>{
      const labels=call.args.map((arg,index)=>call.argLabels[index]??(arg.kind==='name'?arg.name:''));
      return `${this.expression(call.args[labels.indexOf('name')])} to ${this.expression(call.args[labels.indexOf('value')])}`;
    })};
  }
  private statements(body:Stmt[]): FlowNode[] {
    return body.flatMap(stmt=>this.statement(stmt));
  }
  private statement(stmt:Stmt): FlowNode[] {
    const nested=(body:Stmt[])=>this.statements(body);
    switch(stmt.kind) {
      case 'assign': {
        if(stmt.target.kind==='name') {
          const type=stmt.declaredType??this.checked.expressionTypes.get(stmt.value);
          if(type)this.locals.set(stmt.target.name,{name:type.name,args:[],nullable:type.nullable,optional:type.optional,span:stmt.span});
          else if(stmt.value.kind==='call'&&stmt.value.callee.kind==='name') {const def=this.definition(stmt.value.callee.name);if(def?.node.kind==='class')this.locals.set(stmt.target.name,{name:def.name,args:[],nullable:false,span:stmt.span});}
        }
        const target=this.expression(stmt.target)+(stmt.declaredType?' of type '+this.type(stmt.declaredType):'');
        const headers=this.headerFields(stmt.value);
        const action=headers?sequence(`Set ${target} from ${this.expression(headers.base)} by adding these header fields in order`,headers.fields):
          this.joinedText(target,stmt.value)??step(`Set ${target} to ${this.expression(stmt.value)}.`);
        return stmt.ownership==='own'?[action,step(`${target} owns this value.`)]:[action];
      }
      case 'destructure':return [step(`Split ${this.expression(stmt.value)} into ${stmt.names.map(code).join(', ')} in order.`)];
      case 'expr': {
        const action=stmt.expr.kind==='literal'&&stmt.expr.value===null?'Continue':stmt.expr.kind==='call'?
          this.call(stmt.expr):'Evaluate '+this.expression(stmt.expr);
        return [step(action[0].toUpperCase()+action.slice(1)+'.')];
      }
      case 'return': {
        if(!stmt.value)return [step('Return.')];
        const headers=this.headerFields(stmt.value);
        if(headers)return [sequence(`Return headers starting with ${this.expression(headers.base)} and adding these fields in order`,headers.fields)];
        const joined=this.joinedText('the return value',stmt.value);
        return joined?[joined,step('Return it.')]:[step('Return '+this.expression(stmt.value)+'.')];
      }
      case 'throw':return [step('Fail with '+this.expression(stmt.value)+'.')];
      case 'yield':return [step('Send '+this.expression(stmt.value)+' as the next stream item.')];
      case 'if':return [block('If '+this.condition(stmt.test),nested(stmt.then)),...(stmt.otherwise.length?[block('Otherwise',nested(stmt.otherwise))]:[])];
      case 'while':return [block('While '+this.condition(stmt.test),nested(stmt.body))];
      case 'for':return [block('For each '+stmt.names.map(code).join(' and ')+' in a snapshot of '+this.expression(stmt.iterable),nested(stmt.body))];
      case 'match':return [block('Match '+this.expression(stmt.value),stmt.cases.map(clause=>{
        const pattern=clause.pattern==='else'?'Any remaining case':clause.pattern==='some'?'A present, non-null value, named '+code(clause.name!):
          clause.pattern==='type'?'A value that satisfies '+this.type(clause.type!)+', named '+code(clause.name!):
          clause.pattern==='literal'?this.expression(clause.literal!):'A null value, including omitted optional input';
        return block(pattern,nested(clause.body));
      }))];
      case 'try':return [block('Try',nested(stmt.body)),...stmt.catches.map(clause=>block('Catch '+this.type(clause.type)+' as '+code(clause.name),nested(clause.body))),
        ...(stmt.always?[block('Always',nested(stmt.always))]:[])];
      case 'unsafe':return [block('Use native code with its declared contract',nested(stmt.body))];
      case 'borrow':return [block('Mutably borrow '+code(stmt.name)+' for this block',nested(stmt.body))];
      case 'scope':return [block('In a scope that joins child tasks and releases local values on exit',nested(stmt.body))];
      case 'lock':return [block('Lock '+this.expression(stmt.value)+' as mutable '+code(stmt.name)+' for this block',nested(stmt.body))];
      case 'freeze':return [step('Freeze '+this.expression(stmt.value)+' as '+code(stmt.name)+'. Share the immutable value without copying it.')];
      case 'serve':return [step('Serve '+stmt.names.map(name=>{const def=this.definition(name);return def?this.link(def):code(name);}).join(', ')+' on port '+this.expression(stmt.port)+'.')];
      default:return unreachable(stmt);
    }
  }
  private condition(expr:Expr): string {
    return this.expression(expr)+(['binary','unary'].includes(expr.kind)?'':' is true');
  }
  private binding(binding:BindDecl): string {
    const info=this.checked.bindings.find(info=>info.declaration===binding);
    const def=this.definition(binding.target.name);this.use(def);
    const lifetime=binding.lifetime??info?.lifetime;
    const key=binding.key+(binding.keyTypeArgs.length?'<'+binding.keyTypeArgs.map(type=>typeName(type)).join(', ')+'>':'');
    return (`Provide ${def?this.link(def,def.name,typeName(binding.target)):this.type(binding.target)} for ${code(key)}. `+
      (lifetime==='shared'?'Share one instance. ':lifetime==='scoped'?'Share one instance per scope. ':lifetime==='fresh'?'Create one instance per resolve. ':'Reuse stateless instances; create stateful instances per resolve. ')+
      (binding.sharedMutation?'Allow shared mutation. ':'')+
      (info?.dependencies.length?'Needs '+info.dependencies.map(code).join(', ')+'. ':'')).trimEnd();
  }
  private callable(method:MethodDecl, owner?:Definition): SpecNode {
    this.locals=new Map(owner&&'fields' in owner.node?fieldsOf(owner.node as ClassDecl).map(field=>[field.name,field.type]):[]);
    const name=owner&&owner.node.kind!=='function'?`${owner.name}.${method.name}`:method.name;
    const documentation=callableDocumentation(this.checked.project,method,owner);
    const children:SpecNode[]=[];
    if(method.name.startsWith('_'))children.push(paragraph('Private to its defining scope.'));
    const notes=this.notes(documentation);
    if(notes)children.push(paragraph(notes));
    children.push(...this.contract(method,documentation),...this.layers(method));
    if(method.body)children.push(flow(this.statements(method.body)));
    else if(method.externC)children.push(paragraph('Native C implementation; only its declared contract is visible here.'));
    return this.heading(name,method.span,owner&&owner.node.kind!=='function'?3:2,children);
  }
  private exportLine(item:Extract<TopLevel,{kind:'export'}>): string {
    const folder=this.file.builtin?libraryChild(this.checked.project.libraries,dirname(this.file.path),item.name):join(dirname(this.file.path),item.name);
    const file=item.folder?join(folder,'export.aug'):join(dirname(this.file.path),item.from+'.aug');
    this.enqueue(file);
    return `Export ${item.folder?'the folder ':'the declaration '}${code(item.name)} from [${code(basename(file))}](${url(relative(dirname(this.docs.get(this.file.path)!),this.docs.get(file)!))}${item.folder?'':'#'+encodeURIComponent(anchor(item.name))}).`;
  }
  private providerLine(item:BindDecl|Extract<TopLevel,{kind:'include'}>): string {
    if(item.kind==='bind')return this.binding(item);
    const def=this.definition(item.name);
    return 'Include providers from '+(def?this.link(def):code(item.name))+'.';
  }
  private declaration(item:TopLevel): SpecNode {
    switch(item.kind) {
      case 'function':return this.callable(item);
      case 'class': {
        const def=this.definition(item.name)!;this.locals=new Map();
        const documentation=javadocBefore(this.file.source,item.annotations?.[0]?.span.start??item.span.start);
        const children:SpecNode[]=[];
        const generics=this.generics(item), notes=this.notes(documentation);
        const inputs=this.inputs(item.fields,true,this.file.path,documentation?.parameters);
        const implementsText=item.implements.length?'Implements '+item.implements.map(type=>{const def=this.definition(type.name);return def?this.link(def):this.type(type);}).join(', ')+'.':'';
        const introduction=[notes,implementsText,item.name.startsWith('_')?'Private to this file.':'',generics].filter(Boolean).join(' ');
        if(introduction)children.push(paragraph(introduction));
        if(inputs)children.push(paragraph(inputs));
        children.push(...this.layers(item));
        if(item.validationErrors?.length)children.push(paragraph('Construction can fail with '+item.validationErrors.map(type=>this.type(type)).join(', ')+'.'));
        if(item.stateFields?.length)children.push(paragraph('Initialize fields:'),list(item.stateFields.map(field=>{this.locals.set(field.name,field.type);return `${code(field.name)} (${this.type(field.type)}) = ${this.expression(field.initializer)}; ${field.mutable?'mutable':'read-only'}${field.name.startsWith('_')?', private':''}.`;})));
        if(item.constructorBody)children.push(this.heading(item.name+'.initialize',item.span,3,[flow(this.statements(item.constructorBody))]));
        if(!item.record) {
          const defaults=this.checked.defaults.get(def.id);
          const inherited=[...(defaults?.values()??[])].filter(info=>!item.methods.some(method=>method.name===info.method.name));
          if(inherited.length)children.push(paragraph('Inherited defaults:'),list(inherited.map(info=>{const parent=this.checked.project.definitions.get(info.from);this.use(parent,info.method);return (parent?this.link(parent,`${parent.name}.${info.method.name}`):code(info.method.name))+'.';})));
        }
        children.push(...item.methods.map(method=>this.callable(method,def)));
        return this.heading(item.name,item.span,2,children,item.record?'immutable record':'class');
      }
      case 'interface':case 'interceptor': {
        const def=this.definition(item.name)!;this.locals=new Map();
        const generics=this.generics(item),notes=this.notes(javadocBefore(this.file.source,item.span.start));
        const role=item.kind==='interceptor'?'interceptor':item.capability?'capability interface':'interface';
        const introduction=[notes,item.name.startsWith('_')?'Private to this file.':'',generics].filter(Boolean).join(' ');
        const children:SpecNode[]=introduction?[paragraph(introduction)]:[];
        if(item.kind==='interface'&&item.extends.length)children.push(paragraph('Inherits '+item.extends.map(type=>{const def=this.definition(type.name);return def?this.link(def):this.type(type);}).join(', ')+'.'));
        if(item.kind==='interceptor') {
          const inputs=this.inputs(item.fields,true);
          if(inputs)children.push(paragraph(inputs));
          children.push(paragraph('Creates one interceptor per invocation. Its around operation may delegate once or finish early.'));
        }
        children.push(...item.methods.map(method=>this.callable(method,def)));
        return this.heading(item.name,item.span,2,children,role);
      }
      case 'composition': {
        const notes=this.notes(javadocBefore(this.file.source,item.span.start));
        return this.heading(item.name,item.span,2,[...(notes?[paragraph(notes)]:[]),paragraph('Provides these dependencies before startup:'),list(item.bindings.map(binding=>this.binding(binding)))]);
      }
      case 'test':return this.tests(item);
      case 'bind':case 'include':return paragraph(this.providerLine(item));
      case 'export':return paragraph(this.exportLine(item));
      case 'import':return paragraph('');
      default:return flow(this.statement(item));
    }
  }
  private tests(suite:TestDecl): SpecNode {
    this.locals=new Map();const children:SpecNode[]=[paragraph('Tests '+this.type(suite.type)+'. Each case gets fresh setup and dependencies.')];
      for(const group of suite.groups) {
      this.locals=new Map();const groupChildren:SpecNode[]=[];
      if(group.setup.length)groupChildren.push(paragraph('Setup for each case:'),flow(group.setup.flatMap(entry=>
        entry.kind==='bind'||entry.kind==='include'?[step(this.providerLine(entry))]:this.statement(entry as Stmt))));
      const setupLocals=new Map(this.locals);
      for(const test of group.cases) {
        this.locals=new Map(setupLocals);const caseChildren:SpecNode[]=[];
        if(test.parameters)caseChildren.push(paragraph('Run once for each row of '+test.rows!.map(row=>this.expression(row)).join('; ')+'. Bind row positions to '+test.parameters.map(code).join(', ')+'.'));
        caseChildren.push(flow(this.statements(test.body)));
        groupChildren.push(section(code(test.name),4,caseChildren,undefined,this.source(test.span)));
      }
      children.push(section(code(group.name),3,groupChildren));
    }
    return this.heading(this.testTitle(suite),suite.span,2,children);
  }
  private testTitle(suite:TestDecl): string {
    return 'test '+suite.type.name+(suite.name===suite.type.name?'':' '+suite.name);
  }
  private dependencySurface(): SpecNode|undefined {
    if(!this.used.size)return;
    const entries=[...this.used.values()].sort((a,b)=>compare(relative(this.checked.project.root,this.docs.get(a.def.file)!)+':'+a.def.name,relative(this.checked.project.root,this.docs.get(b.def.file)!)+':'+b.def.name));
    const lines:string[]=[];
    for(const entry of entries) {
      const def=entry.def, node=def.node;
      let text=node.kind==='function'?this.dependencyOperation(node,def):this.link(def);
      const imported=this.file.items.find(item=>item.kind==='import'&&(this.checked.project.imports.get(item)??[]).some(imported=>imported.id===def.id));
      if(imported?.kind==='import')text+=' from '+code(imported.from.join('.'))+(imported.everything?' through import everything':'');
      const details:string[]=[];
      if(node.kind==='class'&&entry.constructed)details.push('construct with '+this.shortInputs(node.fields,def.file)+
        (node.validationErrors?.length?'; can fail with '+node.validationErrors.map(type=>this.type(type,def.file)).join(', '):''));
      if(node.kind==='class'&&entry.fields.size)for(const name of [...entry.fields].sort(compare)){
        const field=fieldsOf(node).find(field=>field.name===name);
        if(field)details.push('read '+code(name)+' ('+this.type(field.type,def.file)+')'+(field.mutable?', mutable':''));
      }
      if('methods' in node)for(const method of [...entry.operations].sort((a,b)=>compare(a.name,b.name)))details.push(this.dependencyOperation(method,def));
      text+=(details.length?': '+details.join('; '):'')+'.';
      lines.push(text);
    }
    return section('Dependencies',2,[list(lines)]);
  }
  private shortInputs(params:Param[], file:string): string {
    return params.filter(param=>!param.injected).map(param=>code(param.label??param.name)+': '+this.type(param.type,file)+
      (param.source?' from HTTP '+param.source.kind+(param.source.name?' '+code(param.source.name):''):'')).join(', ')||'no caller inputs';
  }
  private dependencyOperation(method:MethodDecl, owner:Definition): string {
    const layers=this.checked.interceptorPlans.get(method)??[];
    const errors=[...new Set([...method.throws.map(type=>typeName(type)),...layers.flatMap(layer=>layer.errors.map(tyName))])];
    const name=owner.node.kind==='function'?owner.name:owner.name+'.'+method.name;
    let text=this.link(owner,name,owner.node.kind==='function'?owner.name:method.name)+(method.typeParams.length?'<'+method.typeParams.map(code).join(', ')+'>':'')+
      ' ('+this.shortInputs(method.params,method.span.file)+') → '+this.type(method.returns,method.span.file);
    if(errors.length)text+='; can fail with '+errors.map(code).join(', ');
    return text;
  }
  render(): string {
    const exports=this.file.items.filter(item=>item.kind==='export');
    const declarations=this.file.items.filter(item=>['class','interface','interceptor','function','composition'].includes(item.kind));
    const providers=this.file.items.filter(item=>item.kind==='bind'||item.kind==='include');
    const startup=this.file.items.filter(item=>item.kind!=='import'&&item.kind!=='export'&&item.kind!=='test'&&item.kind!=='bind'&&item.kind!=='include'&&!declarations.includes(item));
    const children:SpecNode[]=[];
    if(basename(this.file.path)==='main.aug') {
      const project=this.checked.project;
      if(project.files.get(this.file.path)?.items.some(item=>item.kind==='serve'))children.push(section('HTTP configuration',2,[paragraph(
        `Listen on ${code(project.config.web.host)}. Limit request bodies to ${project.config.web.body_limit} bytes and buffered responses to ${project.config.web.response_limit} bytes. `+
        (project.config.web.tls.certificate?'Use TLS. ':'')+
        (project.config.web.http3?'Enable HTTP/3. ':'')+
        (project.config.openapi.enabled?`Serve OpenAPI at ${code(project.config.openapi.path)} and API docs at ${code(project.config.openapi.docs)}. `:''))]));
    }
    // Build the checked explanation first; rendering decides all spacing.
    if(exports.length)children.push(section('Exports',2,[list(exports.map(item=>this.exportLine(item as Extract<TopLevel,{kind:'export'}>)))]));
    if(providers.length)children.push(section('Providers',2,[list(providers.map(item=>this.providerLine(item as BindDecl|Extract<TopLevel,{kind:'include'}>)))]));
    if(startup.length)children.push(section('Startup',2,[flow(startup.flatMap(item=>this.statement(item as Stmt)))]));
    children.push(...declarations.sort((a,b)=>Number('name' in a&&a.name.startsWith('_'))-Number('name' in b&&b.name.startsWith('_'))).map(item=>this.declaration(item)));
    children.push(...this.file.items.filter(item=>item.kind==='test').map(item=>this.declaration(item)));
    if(!children.length)children.push(paragraph('This file declares no operations.'));
    // Dependency signatures can reference more imported types. Walk until the surface is closed.
    let surface:SpecNode|undefined, size=-1;
    do {size=this.used.size;surface=this.dependencySurface();} while(this.used.size!==size);
    if(surface)children.push(surface);
    const builtins=this.builtinSurface();if(builtins)children.push(builtins);
    return generated+'\n\n'+renderSpecTree(section(code(basename(this.file.path)),1,children));
  }
  private builtinSurface(): SpecNode|undefined {
    if(!this.builtins.size&&!this.properties.size)return;
    const items=[...this.properties].sort(([a],[b])=>compare(a,b)).map(([name,property])=>
      `${code(name)}: ${property.documentation}`);
    items.push(...[...this.builtins].sort(([a],[b])=>compare(a,b)).map(([name,operation])=>
      `${code(name)}: ${operation.documentation}`));
    return section('Built-ins · [reference](https://greenpandastudios.github.io/augscript/language-constructs)',2,[list(items)]);
  }
}

/** Check generated artifacts without writing; protect neighboring handwritten documents. */
export function updateSpecs(checked:CheckedProject, check=false, options:SpecOptions={}): {files:number; stale:string[]} {
  const outputs=generateSpecs(checked,options), root=checked.project.root;
  const manifest=join(root,'.aug-spec','manifest.json');
  let previous:string[]=[];
  if(options.manifest!==false&&existsSync(manifest)) {
    const saved=JSON.parse(readFileSync(manifest,'utf8')) as {format:number;files:string[]};
    if(saved.format!==1||!Array.isArray(saved.files)||saved.files.some(path=>typeof path!=='string'||relative(root,resolve(root,path)).startsWith('..')||!path.endsWith('.aug')&&!path.endsWith('.aug.md')))
      throw new Error('Invalid generated specification manifest');
    previous=saved.files.map(path=>resolve(root,path));
  }
  const names=new Set(outputs.map(output=>output.path));
  const removed=previous.filter(path=>!names.has(path)&&existsSync(path));
  const stale=outputs.filter(output=>!existsSync(output.path)||readFileSync(output.path,'utf8')!==output.text).map(output=>relative(root,output.path));
  stale.push(...removed.map(path=>relative(root,path)));
  const manifestText=JSON.stringify({format:1,files:outputs.map(output=>relative(root,output.path).replaceAll('\\','/')),digest:hash(outputs.map(output=>output.text).join('\0'))},null,2)+'\n';
  if(options.manifest!==false&&(!existsSync(manifest)||readFileSync(manifest,'utf8')!==manifestText))stale.push('.aug-spec/manifest.json');
  if(check)return {files:outputs.length,stale};
  if(options.manifest!==false&&(existsSync(dirname(manifest))&&lstatSync(dirname(manifest)).isSymbolicLink()||existsSync(manifest)&&lstatSync(manifest).isSymbolicLink()))
    throw new Error('Specification manifest must not be a symbolic link');
  for(const output of outputs) {
    let parent=dirname(output.path);
    // Trust the project root, including platform aliases such as macOS /var.
    while(parent!==root&&!relative(root,parent).startsWith('..')&&parent!==dirname(parent)) {
      if(existsSync(parent)&&lstatSync(parent).isSymbolicLink())throw new Error(`Specification output directory is a symbolic link: ${parent}`);
      parent=dirname(parent);
    }
    if(existsSync(output.path)) {
      if(lstatSync(output.path).isSymbolicLink())throw new Error(`Specification output is a symbolic link: ${output.path}`);
      const text=readFileSync(output.path,'utf8');
      if(!text.startsWith(generated)&&!text.startsWith(copied))throw new Error(`Refusing to overwrite handwritten file ${output.path}`);
    }
  }
  for(const output of outputs) {
    if(existsSync(output.path)&&readFileSync(output.path,'utf8')===output.text)continue;
    mkdirSync(dirname(output.path),{recursive:true});
    const temporary=output.path+'.aug-spec-tmp';
    try {writeFileSync(temporary,output.text,{flag:'wx'});renameSync(temporary,output.path);} finally {if(existsSync(temporary))rmSync(temporary);}
  }
  for(const path of removed) {
    const text=readFileSync(path,'utf8');
    if(text.startsWith(generated)||text.startsWith(copied))rmSync(path);
  }
  if(options.manifest!==false) {
    mkdirSync(dirname(manifest),{recursive:true});
    if(!existsSync(manifest)||readFileSync(manifest,'utf8')!==manifestText) {
      const temporary=manifest+'.aug-spec-tmp';
      try {writeFileSync(temporary,manifestText,{flag:'wx'});renameSync(temporary,manifest);} finally {if(existsSync(temporary))rmSync(temporary);}
    }
  }
  return {files:outputs.length,stale:[]};
}
